// The command.

/** Bash/zsh/fish from the basename of $SHELL; undefined otherwise. */
export function shellFromEnv(env: NodeJS.ProcessEnv = process.env): Shell | undefined {
  const raw = env['SHELL'];
  if (typeof raw !== 'string' || raw === '') return undefined;
  const base = raw.slice(raw.lastIndexOf('/') + 1);
  return SUPPORTED_SHELLS.find((s) => s === base);
}

export function shellScript(shell: Shell, program: Command): string {
  if (shell === 'bash') return generateBashCompletion(program);
  if (shell === 'zsh') return generateZshCompletion(program);
  return generateFishCompletion(program);
}

export async function runCompletion(
  ctx: CliContext,
  shellArg: string | undefined,
  program: Command,
): Promise<void> {
  const r = new Renderer({ out: ctx.io.out, err: ctx.io.err, json: ctx.json, debug: ctx.debug });

  let shell: Shell | undefined;
  if (shellArg !== undefined) {
    const found = SUPPORTED_SHELLS.find((s) => s === shellArg.trim().toLowerCase());
    if (found === undefined) {
      r.fail(`Unknown shell: ${shellArg} — expected bash, zsh, or fish.`);
      process.exitCode = 1;
      return;
    }
    shell = found;
  } else {
    shell = shellFromEnv();
  }

  if (shell === undefined) {
    r.fail('Usage: selora completion <bash|zsh|fish>');
    r.bullet('Prints a completion script for the given shell to stdout.');
    r.bullet('bash:  eval "$(selora completion bash)"');
    r.bullet('zsh:   source it from .zshrc, or drop it on your fpath as _selora');
    r.bullet('fish:  selora completion fish > ~/.config/fish/completions/selora.fish');
    process.exitCode = 1;
    return;
  }

  const script = shellScript(shell, program);
  if (ctx.json) {
    r.jsonOut({ ok: true, shell, script });
    return;
  }
  ctx.io.out(script);
}
